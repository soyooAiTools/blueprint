function safeArray(value) {
  return Array.isArray(value) ? value : [];
}

function readJson(filePath) {
  return JSON.parse(fs.readFileSync(filePath, 'utf8'));
}

function readJsonIfExists(filePath) {
  return fs.existsSync(filePath) ? readJson(filePath) : null;
}

function writeFile(filePath, text) {
  fs.mkdirSync(path.dirname(filePath), { recursive: true });
  fs.writeFileSync(filePath, text);
}

function writeJson(filePath, value) {
  writeFile(filePath, JSON.stringify(value, null, 2) + '\n');
}

function sha256Text(text) {
  return crypto.createHash('sha256').update(String(text || '')).digest('hex');
}

function unityGuidForRel(relPath) {
  return crypto.createHash('sha1').update('unitycomponent-v1-meta:' + relPath.split(path.sep).join('/')).digest('hex').slice(0, 32);
}

function slgRel() {
  return [SLG_SCRIPT_ROOT].concat(Array.prototype.slice.call(arguments)).join('/');
}

function slgPath(root) {
  return path.join.apply(path, [root, 'Assets', 'SLGFrameWork', 'Scripts'].concat(Array.prototype.slice.call(arguments, 1)));
}

function sanitizeId(value, fallback) {
  var text = String(value || fallback || 'Item').replace(/[^A-Za-z0-9_]+/g, '_').replace(/^_+|_+$/g, '');
  if (!text) text = String(fallback || 'Item');
  if (!/^[A-Za-z_]/.test(text)) text = '_' + text;
  return text;
}

function csString(value) {
  return JSON.stringify(String(value == null ? '' : value));
}

function fieldName(name) {
  var id = sanitizeId(name, 'item');
  return id.charAt(0).toLowerCase() + id.slice(1);
}

function componentField(component) {
  var base = String(component || 'component').replace(/Component$/, '');
  return fieldName(base);
}

function header() {
  return [
    '// <auto-generated>',
    '// UnityComponent(3) / SLGFrameWork profile output.',
    '// Source HTML, SourceIR, WebGL and Luna parity contracts are not mutated here.',
    '// </auto-generated>',
    ''
  ].join('\n');
}

function csFile(lines) {
  return header() + lines.join('\n') + '\n';
}

