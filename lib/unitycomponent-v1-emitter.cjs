function unityMetaText(relPath, kind) {
  var guid = unityGuidForRel(relPath);
  if (kind === 'script') {
    return [
      'fileFormatVersion: 2',
      'guid: ' + guid,
      'MonoImporter:',
      '  externalObjects: {}',
      '  serializedVersion: 2',
      '  defaultReferences: []',
      '  executionOrder: 0',
      '  icon: {instanceID: 0}',
      '  userData:',
      '  assetBundleName:',
      '  assetBundleVariant:',
      ''
    ].join('\n');
  }
  return [
    'fileFormatVersion: 2',
    'guid: ' + guid,
    'DefaultImporter:',
    '  externalObjects: {}',
    '  userData:',
    '  assetBundleName:',
    '  assetBundleVariant:',
    ''
  ].join('\n');
}

function writeMetas(root) {
  function walk(dir) {
    if (!fs.existsSync(dir)) return;
    fs.readdirSync(dir).forEach(function(name) {
      var file = path.join(dir, name);
      var stat = fs.statSync(file);
      if (stat.isDirectory()) {
        walk(file);
        return;
      }
      if (!/\.(cs|prefab|json)$/i.test(file)) return;
      var relPath = path.relative(root, file).split(path.sep).join('/');
      var kind = /\.cs$/i.test(file) ? 'script' : 'asset';
      writeFile(file + '.meta', unityMetaText(relPath, kind));
    });
  }
  walk(path.join(root, 'Assets'));
}

