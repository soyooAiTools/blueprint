function writeObjectPoolComponent(root) {
  writeFile(slgPath(root, 'Component', 'ObjectPoolComponent', 'ObjectPoolComponent.cs'), csFile([
    'using System;',
    'using System.Collections.Generic;',
    'using UnityEngine;',
    '',
    '[Serializable]',
    'public class ObjectPoolComponent : BaseComponent',
    '{',
    '    public GameObject ObjectPrefab;',
    '    public Queue<GameObject> pool = new Queue<GameObject>();',
    '    public List<GameObject> OpenObjectList = new List<GameObject>();',
    '',
    '    public GameObject CreateNewObject(bool isActive)',
    '    {',
    '        if (ObjectPrefab == null) return null;',
    '        GameObject go = MonoBehaviour.Instantiate(ObjectPrefab);',
    '        go.SetActive(isActive);',
    '        if (!isActive) pool.Enqueue(go);',
    '        return go;',
    '    }',
    '',
    '    public GameObject SpawnObject(Vector3 position, Quaternion rotation)',
    '    {',
    '        GameObject go = pool.Count > 0 ? pool.Dequeue() : CreateNewObject(true);',
    '        if (go == null) return null;',
    '        go.transform.position = position;',
    '        go.transform.rotation = rotation;',
    '        go.SetActive(true);',
    '        OpenObjectList.Add(go);',
    '        Entity spawnedEntity = go.GetComponent<Entity>();',
    '        if (spawnedEntity != null) spawnedEntity.objectPoolComponentReference = this;',
    '        return go;',
    '    }',
    '',
    '    public void Recycle(GameObject go)',
    '    {',
    '        if (go == null || pool.Contains(go)) return;',
    '        go.SetActive(false);',
    '        OpenObjectList.Remove(go);',
    '        go.transform.SetParent(null);',
    '        pool.Enqueue(go);',
    '    }',
    '',
    '    public void RecycleAll()',
    '    {',
    '        for (int i = 0; i < OpenObjectList.Count; i++)',
    '        {',
    '            GameObject go = OpenObjectList[i];',
    '            if (go == null) continue;',
    '            go.SetActive(false);',
    '            go.transform.SetParent(null);',
    '            pool.Enqueue(go);',
    '        }',
    '        OpenObjectList.Clear();',
    '    }',
    '',
    '    public void AddReference(GameObject go)',
    '    {',
    '        if (go != null && !OpenObjectList.Contains(go)) OpenObjectList.Add(go);',
    '    }',
    '}'
  ]));
}

function generatedDeliveryDataText(spec) {
  var phaseLines = safeArray(spec.phases).map(function(phase) {
    return '            new PhaseData { PhaseId = ' + csString(phase.id) + ', GuideText = ' + csString(phase.guideText) + ', ShowEntities = new string[] { ' + safeArray(phase.showEntities).map(csString).join(', ') + ' }, TargetSequence = new string[] { ' + safeArray(phase.targetSequence).map(csString).join(', ') + ' } }';
  });
  var entityLines = safeArray(spec.entities).map(function(entity) {
    return '            new EntityData { SourceId = ' + csString(entity.sourceId) + ', UnityClass = ' + csString(entity.unityClass) + ', BindingKind = ' + csString(entity.bindingKind) + ', PrefabPath = ' + csString(entity.prefabPath) + ' }';
  });
  var sceneLines = safeArray(spec.sceneRefs).map(function(item) {
    return '            new SceneRefData { Id = ' + csString(item.id) + ', SourceId = ' + csString(item.sourceId) + ', PrefabPath = ' + csString(item.prefabPath) + ' }';
  });
  var poolLines = safeArray(spec.poolArchetypes).map(function(item) {
    return '            new PoolArchetypeData { Id = ' + csString(item.id) + ', SourceId = ' + csString(item.sourceId) + ', PrefabPath = ' + csString(item.prefabPath) + ', Preload = ' + (Number(item.preload) || 0) + ' }';
  });
  var uiLines = safeArray(spec.uiRefs).map(function(item) {
    return '            new UiRefData { Id = ' + csString(item.id) + ', Role = ' + csString(item.role) + ', SourceId = ' + csString(item.sourceId || '') + ', Required = ' + (item.required === false ? 'false' : 'true') + ' }';
  });
  var assetLines = safeArray(spec.assetBindings).map(function(item) {
    return '            new AssetBindingData { AssetId = ' + csString(item.assetId) + ', Kind = ' + csString(item.kind) + ', Source = ' + csString(item.source || '') + ', PrefabPath = ' + csString(item.prefabPath || '') + ', MaterialPath = ' + csString(item.materialPath || '') + ', ActionId = ' + csString(item.actionId || '') + ', Status = ' + csString(item.status || '') + ' }';
  });

  function arrayBlock(type, name, lines) {
    return [
      '    public static readonly ' + type + '[] ' + name + ' = new ' + type + '[]',
      '    {'
    ].concat(lines.map(function(line, index) {
      return line + (index < lines.length - 1 ? ',' : '');
    }), [
      '    };'
    ]);
  }

  return csFile([
    'using UnityEngine;',
    '',
    '[System.Serializable]',
    'public class PhaseData',
    '{',
    '    public string PhaseId;',
    '    public string GuideText;',
    '    public string[] ShowEntities;',
    '    public string[] TargetSequence;',
    '}',
    '',
    '[System.Serializable]',
    'public class EntityData',
    '{',
    '    public string SourceId;',
    '    public string UnityClass;',
    '    public string BindingKind;',
    '    public string PrefabPath;',
    '}',
    '',
    '[System.Serializable]',
    'public class SceneRefData',
    '{',
    '    public string Id;',
    '    public string SourceId;',
    '    public string PrefabPath;',
    '}',
    '',
    '[System.Serializable]',
    'public class PoolArchetypeData',
    '{',
    '    public string Id;',
    '    public string SourceId;',
    '    public string PrefabPath;',
    '    public int Preload;',
    '}',
    '',
    '[System.Serializable]',
    'public class UiRefData',
    '{',
    '    public string Id;',
    '    public string Role;',
    '    public string SourceId;',
    '    public bool Required;',
    '}',
    '',
    '[System.Serializable]',
    'public class AssetBindingData',
    '{',
    '    public string AssetId;',
    '    public string Kind;',
    '    public string Source;',
    '    public string PrefabPath;',
    '    public string MaterialPath;',
    '    public string ActionId;',
    '    public string Status;',
    '}',
    '',
    'public static class GeneratedDeliveryData',
    '{'
  ].concat(
    arrayBlock('PhaseData', 'Phases', phaseLines),
    [''],
    arrayBlock('EntityData', 'Entities', entityLines),
    [''],
    arrayBlock('SceneRefData', 'SceneRefs', sceneLines),
    [''],
    arrayBlock('PoolArchetypeData', 'PoolArchetypes', poolLines),
    [''],
    arrayBlock('UiRefData', 'UiRefs', uiLines),
    [''],
    arrayBlock('AssetBindingData', 'AssetBindings', assetLines),
    ['}']
  ));
}

