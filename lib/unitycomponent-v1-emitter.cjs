    '        if (!entity.IsInit) entity.OnAwake();',
    '        entity.OnStart();',
    '    }',
    '',
    '    public void UnRegistarEntity(Entity entity)',
    '    {',
    '        if (entity == null) return;',
    '        entities.Remove(entity);',
