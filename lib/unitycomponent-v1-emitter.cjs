function loadArtifacts(dir) {
  return {
    sourceIr: readJson(path.join(dir, 'source-ir.json')),
    gameSchema: readJsonIfExists(path.join(dir, 'gameschema.json')),
    playableSceneIr: readJsonIfExists(path.join(dir, 'playable-scene-ir.json')),
    assetManifest: readJsonIfExists(path.join(dir, 'asset-manifest.json')),
    unityAssetPlan: readJsonIfExists(path.join(dir, 'unity-asset-plan.json')) ||
      readJsonIfExists(path.join(dir, 'blueprint-unity-asset-plan.json'))
  };
}

function emitUnityComponentProject(spec, outDir, options) {
  options = options || {};
  var profile = profiles.resolveProfile('unitycomponent-v1');
  var root = path.resolve(outDir);
  fs.mkdirSync(root, { recursive: true });
  writeUnityProjectScaffold(root);
  writeBase(root);
  writeManagers(root);
  writeBlueprintDeliveryRuntime(root, spec);
  writeComponents(root, spec);
  writeEntities(root, spec);
  writeJson(path.join(root, 'Assets', 'BlueprintDelivery', 'UnityDeliverySpec.json'), projector.minimalUnityVisibleSpec(spec));
  if (options.sourceIr) writeJson(path.join(root, 'source-ir.json'), options.sourceIr);
  writeGameEntryPrefab(root);
  writeFrameworkTemplateManifest(root);
  writeMetas(root);
  var report = hardgate.writeReport(root, path.join(root, 'UNITYCOMPONENT_V1_VALIDATION.json'), { profile: profile.id });
  return {
    root: root,
    spec: spec,
    report: report
  };
}

function emitFromArtifacts(artifactsDir, outDir, options) {
  options = options || {};
  var artifacts = loadArtifacts(path.resolve(artifactsDir));
  var spec = projector.buildUnityDeliverySpec(artifacts, {
    profile: 'unitycomponent-v1',
    generatedAt: options.generatedAt
  });
  projector.assertDeliverySpecSourceParity(spec, artifacts.sourceIr);
  return emitUnityComponentProject(spec, outDir, { sourceIr: artifacts.sourceIr });
}

function parseArgs(argv) {
  var args = argv || process.argv.slice(2);
  var parsed = { artifactsDir: '', outDir: '' };
  for (var i = 0; i < args.length; i++) {
    var arg = args[i];
    if (!parsed.artifactsDir) parsed.artifactsDir = arg;
    else if (!parsed.outDir) parsed.outDir = arg;
    else throw new Error('Unexpected argument: ' + arg);
  }
  if (!parsed.artifactsDir || !parsed.outDir) {
    throw new Error('Usage: node lib/unitycomponent-v1-emitter.cjs <source-ir-artifacts-dir> <unity-out-dir>');
  }
  return parsed;
}

if (require.main === module) {
  try {
    var parsed = parseArgs();
    var result = emitFromArtifacts(parsed.artifactsDir, parsed.outDir);
    process.stdout.write(JSON.stringify({
      ok: result.report.passed,
      root: result.root,
      semanticHash: result.spec.semanticHash,
      validation: result.report.summary
    }, null, 2) + '\n');
    if (!result.report.passed) process.exit(1);
  } catch (err) {
    console.error(err && err.stack || err);
    process.exit(1);
  }
}

