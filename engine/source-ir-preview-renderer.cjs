function buildSourceIrPreviewHtml(sourceIr, options) {
  options = options || {};
  var ir = normalizeSourceSceneIr(sourceIr, options);
  var projection = projectSourceSceneIrToLegacy(ir);
  var title = ir.project && ir.project.name || 'SourceIR preview';
  var threeLoaderTags = buildThreeLoaderTags(options);
  return [
    '<!doctype html>',
    '<html>',
    '<head>',
    '<meta charset="utf-8">',
    '<meta name="viewport" content="width=device-width,initial-scale=1">',
    '<title>' + String(title).replace(/[<>&]/g, '') + '</title>',
    '</head>',
    '<body>',
    '<script>',
    'window.__BP_SOURCE_IR__ = ' + safeInlineJson(ir) + ';',
    'window.__BP_SOURCE_IR_HASH__ = "' + ir.semanticHash + '";',
    'const PHASES = ' + safeInlineJson(projection.PHASES) + ';',
    'const ENTITY_STYLE = ' + safeInlineJson(projection.ENTITY_STYLE) + ';',
    'const ENTITY_POSITIONS = ' + safeInlineJson(projection.ENTITY_POSITIONS) + ';',
    'const SCENE_CONFIG = ' + safeInlineJson(projection.SCENE_CONFIG) + ';',
    '</script>',
  ].concat(threeLoaderTags).concat([
    '<script>',
    buildSourceIrPreviewRendererScript(),
    '</script>',
    '</body>',
    '</html>',
  ]).join('\n');
}

function rewriteHtmlWithSourceIrPreviewRenderer(html, options) {
  options = options || {};
  if (options.requireEmbeddedSourceIr !== false && !/\b__BP_SOURCE_IR__\b/.test(String(html || ''))) {
    throw new Error('SourceIR preview rewrite requires embedded window.__BP_SOURCE_IR__');
  }
  var ir = extractSourceSceneIrFromHtml(String(html || ''), options.sourceHtmlPath || null, {
    generatedAt: options.generatedAt,
    project: options.project || null,
  });
  return buildSourceIrPreviewHtml(ir, {
    generatedAt: options.generatedAt,
    html: '<div id="joystick"></div>',
  });
}

