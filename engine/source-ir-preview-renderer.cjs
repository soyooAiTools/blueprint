    'function driveToPhase(n){ applyPhase(Number(n)); return new Promise(function(resolve){ afterTwoFrames(function(){ renderFrame(); resolve(window.__gameState()); }); }); }',
    'function updatePhaseTimer(){ state.phaseRealTimer = Math.max(0, now() - phaseStartedAt); if (window.requestAnimationFrame) window.requestAnimationFrame(updatePhaseTimer); }',
    'function installJoystick(){',
    '  function setKnob(dx, dy){ refs.knob.style.transform = "translate(" + (dx * 30) + "px," + (dy * 30) + "px)"; }',
    '  document.addEventListener("pointerdown", function(ev){ if (ev.target && ev.target.closest && ev.target.closest("#tip,#resourceBar,#phaseLabel")) return; input.joystick.active = true; input.joystick.originX = ev.clientX || 0; input.joystick.originY = ev.clientY || 0; input.joystick.dx = 0; input.joystick.dy = 0; refs.joystick.style.left = ((ev.clientX || 48) - 48) + "px"; refs.joystick.style.top = ((ev.clientY || 48) - 48) + "px"; refs.joystick.style.bottom = "auto"; setKnob(0,0); });',
    '  document.addEventListener("pointermove", function(ev){ if (!input.joystick.active) return; var dx = Math.max(-1, Math.min(1, ((ev.clientX || 0) - input.joystick.originX) / 42)); var dy = Math.max(-1, Math.min(1, ((ev.clientY || 0) - input.joystick.originY) / 42)); input.joystick.dx = dx; input.joystick.dy = dy; setKnob(dx, dy); });',
    '  function end(){ input.joystick.active = false; input.joystick.dx = 0; input.joystick.dy = 0; setKnob(0,0); }',
    '  document.addEventListener("pointerup", end); document.addEventListener("pointercancel", end);',
    '}',
    'window.setTip = setTip;',
    'window.__gameState = function(){ state.phaseRealTimer = Math.max(0, now() - phaseStartedAt); return state; };',
    'window.__driveToSourcePhase = driveToPhase;',
    'window.__driveToPhase = driveToPhase;',
    'window.__sourceIrPreviewApplyPhase = applyPhase;',
    'refs = ensureShell(); installJoystick(); if (!buildThreeScene()) buildDomModels(); applyPhase(1); renderFrame();',
    'afterTwoFrames(function(){ renderFrame(); window.__fidelityReady = true; });',
    'if (window.requestAnimationFrame) window.requestAnimationFrame(updatePhaseTimer);',
    '}());',
